// Writes app/learn/seed-articles.mjs from the coaching rules and the
// recorded Scryfall fixtures. Re-run when those inputs change.
import { writeFile, readFile } from "node:fs/promises";
import { buildTheoryArticles } from "../app/learn/theory.mjs";
import { buildSetReview } from "../app/learn/set-review.mjs";
import { buildSpotlight } from "../app/learn/spotlight.mjs";
import { COMMANDER_GUIDES } from "../app/commanders/data.mjs";

const now = "2026-10-31";
const staples = JSON.parse(await readFile(new URL("../app/learn/fixtures/staples.json", import.meta.url), "utf8")).cards;
const older = JSON.parse(await readFile(new URL("../app/learn/fixtures/older-set.json", import.meta.url), "utf8"));
const fracture = JSON.parse(await readFile(new URL("../app/learn/fixtures/reality-fracture.json", import.meta.url), "utf8"));
const pool = [...staples, ...older.cards];
const theory = buildTheoryArticles(pool, now);
const review = buildSetReview(fracture, now, theory);
const guide = COMMANDER_GUIDES.find((entry) => entry.slug === "korvold-fae-cursed-king");
const spotlight = buildSpotlight({
  commander: {
    name: guide.card.name,
    mana_cost: guide.card.mana_cost,
    type_line: guide.card.type_line,
    oracle_text: guide.card.oracle_text,
    color_identity: guide.card.color_identity,
  },
  guide,
  pool,
  now,
  existing: [...theory, review],
});
const articles = [...theory, review, spotlight];
const failed = articles.filter((article) => !article?.indexable);
if (failed.length) {
  console.error(failed.map((article) => [article.slug, article.reasons]));
  process.exit(1);
}
const body = `// Generated by scripts/generate-learn-seed.mjs from coaching rules and recorded Scryfall fixtures.\n// Do not hand-edit. Re-run the script.\nexport const SEED_CLOCK = ${JSON.stringify(now)};\nexport const SEED_ARTICLES = ${JSON.stringify(articles, null, 2)};\n`;
await writeFile(new URL("../app/learn/seed-articles.mjs", import.meta.url), body);
console.log(`wrote ${articles.length} articles`);
