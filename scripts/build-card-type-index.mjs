import { readdir, writeFile } from "node:fs/promises";

const source = new URL("../app/set-cards/", import.meta.url);
const files = (await readdir(source)).filter((file) => file.endsWith(".mjs")).sort();
const index = {};
for (const file of files) {
  const module = await import(new URL(file, source));
  for (const card of module.default?.cards || []) {
    const name = String(card?.name || "").trim();
    const typeLine = String(card?.typeLine || "").trim();
    if (name && typeLine && !index[name.toLowerCase()]) index[name.toLowerCase()] = [name, typeLine];
  }
}
const output = `// Generated by scripts/build-card-type-index.mjs from app/set-cards.\nexport default ${JSON.stringify(index)};\n`;
await writeFile(new URL("../worker/card-type-index.mjs", import.meta.url), output, "utf8");
console.log(`Indexed ${Object.keys(index).length} card names from ${files.length} set files.`);
